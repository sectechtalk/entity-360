import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:3600');
  await page.locator('[data-view="licenses"]').click();
  await page.locator('#license-run').click();
  await page.locator('#license-status').filter({ hasText: 'License check complete' }).waitFor();
  assert.match(await page.locator('#license-results').innerText(), /Level 1/);
  assert.match(await page.locator('#license-results').innerText(), /Current tenant inventory/);
  assert.match(await page.locator('#license-results').innerText(), /Unassigned/);
  await page.screenshot({ path: '.runtime/licenses-desktop.png', fullPage: true });
  await page.locator('#license-example').selectOption('personal');
  await page.locator('#license-run').click();
  await page.locator('#consumer-note-form').waitFor();
  assert.ok(!(await page.locator('#license-results').innerText()).includes('Current tenant inventory'));
  assert.match(await page.locator('#license-results').innerText(), /No personal subscription details/);
  await page.locator('#consumer-product').fill('<script>Family</script>');
  await page.locator('#consumer-relationship').selectOption('shared');
  await page.locator('#consumer-note-form button').click();
  assert.match(await page.locator('#license-results').innerText(), /User-reported; not API verified/);
  assert.equal(await page.locator('#license-results script').count(), 0);
  await page.locator('#license-connect').click();
  assert.equal(await page.locator('#personal-login').isVisible(), true);
  await page.locator('#personal-login').click();
  await page.locator('#login-status').filter({ hasText: 'PERSONAL_CLIENT_ID' }).waitFor();
  await page.locator('#connection-dialog .close-dialog').click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '.runtime/licenses-mobile.png', fullPage: true });
  await page.locator('#license-connect').click();
  await page.locator('#demo-profile').selectOption('reader'); await page.locator('#demo-button').click();
  await page.locator('[data-view="licenses"]').click(); await page.locator('#license-run').click();
  await page.locator('#license-status').filter({ hasText: 'Partial evidence' }).waitFor();
  assert.ok(!(await page.locator('#license-results').innerText()).includes('Current tenant inventory'));
  assert.ok(!(await page.locator('#license-results').innerText()).includes('User-reported; not API verified'));
  assert.deepEqual(errors, []);
  console.log('PASS: user/tenant levels, personal billing limits, source permissions, escaped user-reported evidence, connection setup, context clearing and mobile layout.');
} finally { await browser.close(); }
