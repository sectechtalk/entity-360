import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1536, height: 1100 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
await page.goto('http://localhost:3600');
await page.locator('.entity-info h2').filter({ hasText: 'Alex Morgan' }).waitFor();
await page.locator('#event-rows tr').first().waitFor();
assert.equal(await page.locator('#mode-badge').innerText(), 'DEMO DATA');
await page.screenshot({ path: '.runtime/dashboard-desktop.png', fullPage: true });
await page.locator('#event-tab').click();
assert.match(await page.locator('#policy-list').innerText(), /Require compliant device/);
await page.locator('#view-evidence').click();
assert.equal(await page.locator('#evidence-dialog').isVisible(), true);
await page.locator('#evidence-dialog .close-dialog').click();
await page.getByRole('button', { name: 'CLI', exact: true }).click();
assert.match(await page.locator('#event-rows').innerText(), /powershell|Azure CLI/);
assert.doesNotMatch(await page.locator('#event-rows').innerText(), /SharePoint/);
const downloadPromise = page.waitForEvent('download');
await page.locator('#export-button').click();
const download = await downloadPromise;
assert.match(download.suggestedFilename(), /entity-360.*\.csv/);
await page.locator('#range-button').click();
await page.getByRole('button', { name: 'Last 24 hours', exact: true }).click();
await page.locator('#loading').waitFor({ state: 'hidden' });
assert.equal(await page.locator('#range-label').innerText(), 'Last 24 hours');
await page.locator('#entity-search').fill('Finance');
await page.getByRole('option').filter({ hasText: 'Finance API' }).click();
await page.locator('.entity-info h2').filter({ hasText: 'Finance API' }).waitFor();
await page.locator('#loading').waitFor({ state: 'hidden' });
assert.match(await page.locator('#relationship-list').innerText(), /Payments API/);
await page.locator('[data-view="coverage"]').click();
assert.equal(await page.locator('#coverage-panel').isVisible(), true);
await page.locator('#connection-button').click();
await page.locator('#demo-profile').selectOption('reader');
await page.locator('#demo-button').click();
await page.locator('#loading').waitFor({ state: 'hidden' });
await page.locator('#viewer-name').filter({ hasText: 'Casey Rivera' }).waitFor();
assert.equal(await page.locator('.source-link').count(), 3);
assert.doesNotMatch(await page.locator('#source-links').innerText(), /Defender|Purview|Intune/);
await page.locator('[data-view="overview"]').click();
await page.locator('#category-filters [data-category="All"]').click();
await page.locator('#current-tab').click();
await page.locator('#event-tab').click();
assert.doesNotMatch(await page.locator('#policy-list').innerText(), /Require compliant device|Require MFA/);
assert.doesNotMatch(await page.locator('#event-context').innerText(), /Require compliant device/);
await page.locator('#current-tab').click();
await page.locator('#range-button').click();
await page.locator('#from-date').fill('2026-10-09T12:00');
await page.locator('#to-date').fill('2026-10-08T12:00');
await page.getByRole('button', { name: 'Apply timeframe' }).click();
assert.match(await page.locator('#range-error').innerText(), /valid range/);
await page.locator('#from-date').fill('2020-01-01T00:00');
await page.locator('#to-date').fill('2020-01-02T00:00');
await page.getByRole('button', { name: 'Apply timeframe' }).click();
await page.locator('#loading').waitFor({ state: 'hidden' });
assert.equal(await page.locator('#timeline-empty').isVisible(), true);
await page.locator('#range-button').click();
await page.getByRole('button', { name: 'Last 7 days', exact: true }).click();
await page.locator('#loading').waitFor({ state: 'hidden' });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: '.runtime/dashboard-mobile.png', fullPage: true });
const width = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
assert.ok(width.scroll <= width.width + 1, `Mobile overflow: ${JSON.stringify(width)}`);
const guide = await page.context().newPage();
await guide.goto('http://localhost:3600/setup.html');
assert.match(await guide.locator('h1').innerText(), /Connect your Microsoft tenant/);
assert.match(await guide.locator('main').innerText(), /Live tenant access has not yet been verified/);
assert.deepEqual(errors, []);
console.log('PASS: search, event evidence, event policy results, filters, CSV export, timeframe, application relationships, coverage, viewer authorization, desktop/mobile rendering; no browser errors.');
await browser.close();
