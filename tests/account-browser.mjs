import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:3600');
  await page.locator('[data-view="account"]').click();
  assert.equal(await page.locator('#account-panel').isVisible(), true);
  assert.equal(await page.locator('#entity-header').isVisible(), false);
  await page.locator('#account-run').click();
  await page.locator('#account-status').filter({ hasText: 'Account evidence collected' }).waitFor();
  assert.match(await page.locator('#account-identity').innerText(), /morgan.lee@contoso.example/);
  assert.match(await page.locator('#account-cloud').innerText(), /INTUNE_A/);
  const snapshot = { schemaVersion: 1, kind: 'entity360-device-snapshot', host: 'DEVICE02', collectedAt: new Date().toISOString(), windowsAccount: 'DEVICE02\\user', facts: [{ area: 'Identity', key: 'Untrusted text', value: '<img src=x onerror=alert(1)>', source: 'local' }] };
  await page.locator('#account-import').setInputFiles({ name: 'device.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(snapshot)) });
  await page.locator('#account-status').filter({ hasText: 'Imported evidence from DEVICE02' }).waitFor();
  assert.match(await page.locator('#account-local').innerText(), /<img src=x onerror=alert\(1\)>/);
  assert.equal(await page.locator('#account-local img').count(), 0);
  await page.locator('#account-collect').click();
  await page.locator('#account-status').filter({ hasText: 'Local evidence collected on' }).waitFor({ timeout: 15000 }).catch(async e => { console.log('Collector feedback:',await page.locator('#account-status').innerText()); throw e; });
  assert.match(await page.locator('#account-local').innerText(), /server host/);
  await page.screenshot({ path: '.runtime/account-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '.runtime/account-mobile.png', fullPage: true });
  await page.locator('#account-clear-local').click();
  assert.match(await page.locator('#account-local').innerText(), /No snapshot loaded/);
  await page.locator('#account-connect').click();
  await page.locator('#demo-profile').selectOption('reader'); await page.locator('#demo-button').click();
  await page.locator('#account-run').click();
  await page.locator('#account-status').filter({ hasText: 'Partial results' }).waitFor();
  assert.equal(await page.locator('#account-cloud').innerText(), '');
  assert.ok(!(await page.locator('#source-links').innerText()).includes('licenses'));
  await page.locator('[data-view="overview"]').click();
  assert.equal(await page.locator('#account-panel').isVisible(), false);
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('PASS: self account, source permissions, imported-device provenance, XSS escaping, real local collection, clearing, mobile layout, and navigation.');
} finally { await browser.close(); }
