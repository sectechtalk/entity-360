import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:3600');
  await page.locator('#event-rows tr').first().waitFor();
  await page.getByRole('button', { name: 'Sign-in lookup', exact: true }).click();
  assert.equal(await page.locator('#signin-lookback').inputValue(), '3');
  assert.match(await page.locator('#signin-users').inputValue(), /alex.morgan/);
  assert.equal(await page.locator('#range-button').isVisible(), false);
  const run = async () => { await page.locator('#signin-run').click(); await page.locator('#signin-run').filter({ hasText: 'Look up sign-ins' }).waitFor(); };
  await run();
  assert.match(await page.locator('#signin-summary').innerText(), /4 observed sign-ins · 2 groups/);
  assert.match(await page.locator('#signin-rows').innerText(), /×3/);
  await page.locator('[data-signin-group="0"]').click();
  assert.match(await page.locator('#signin-group-details').innerText(), /Authentication methods/);
  assert.match(await page.locator('#signin-group-details').innerText(), /Not returned for this event/);
  assert.equal(await page.locator('[data-signin-record]').count(), 3);
  await page.locator('[data-signin-record="0"]').click();
  assert.equal(await page.locator('#evidence-dialog').isVisible(), true);
  await page.locator('#evidence-dialog .close-dialog').click();
  await page.locator('.signin-options summary').click();
  await page.locator('#signin-noninteractive').check();
  assert.equal(await page.locator('#signin-beta').isChecked(), true);
  await page.locator('#signin-all-policies').check();
  await run();
  assert.match(await page.locator('#signin-summary').innerText(), /5 observed sign-ins/);
  assert.match(await page.locator('#signin-rows').innerText(), /Not Applied|Success|Failure|Interrupted/);
  assert.match(await page.locator('#signin-rows').innerText(), /Not Applied/);
  await page.locator('[data-signin-group="0"]').click();
  assert.match(await page.locator('#signin-group-details').innerText(), /MFA satisfied by claim/);
  assert.match(await page.locator('#signin-group-details').innerText(), /signInFrequency/);
  await page.screenshot({ path: '.runtime/signins-desktop.png', fullPage: true });
  await page.locator('#signin-detail').check(); await run();
  assert.match(await page.locator('#signin-summary').innerText(), /5 observed sign-ins · 5 rows/);
  await page.locator('#signin-lookback-unit').selectOption('days');
  await page.locator('#signin-lookback').fill('1'); await run();
  assert.match(await page.locator('#signin-summary').innerText(), /Last 24 hours/);
  assert.match(await page.locator('#signin-summary').innerText(), /6 observed sign-ins/);
  await page.locator('#signin-use-defaults').click(); await run();
  assert.match(await page.locator('#signin-summary').innerText(), /12 observed sign-ins/);
  await page.locator('#connection-button').click();
  await page.locator('#demo-profile').selectOption('reader'); await page.locator('#demo-button').click();
  await page.locator('#loading').waitFor({ state: 'hidden' });
  await run();
  assert.doesNotMatch(await page.locator('#signin-rows').innerText(), /Require MFA|Require compliant/);
  await page.locator('#signin-users').fill('unknown@example.test'); await run();
  assert.match(await page.locator('#signin-user-status').innerText(), /Records unavailable/);
  assert.equal(await page.locator('.source-link').count(), 0);
  await page.locator('#signin-use-defaults').click(); await run();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.runtime/signins-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1));
  await page.locator('[data-view="overview"]').click();
  assert.equal(await page.locator('#signin-lookup-panel').isVisible(), false);
  assert.equal(await page.locator('#report-content').isVisible(), true);
  assert.deepEqual(errors, []);
  console.log('PASS: sign-in lookback, grouping, authentication/session evidence, raw records, beta options, multiple users, permission filtering, unavailable results, mobile layout and navigation.');
} finally { await browser.close(); }
